namespace {
// A table cell: '|' escaped, never empty.
std::string cell(const char* s) {
  std::string out;
  for (const char* p = s; *p; ++p) out += *p == '|' ? std::string("\\|") : std::string(1, *p);
  return out.empty() ? "-" : out;
}
}  // namespace

std::string markdown() {
  std::string s =
      "# Modding reference\n\n"
      "Every key each file a mod can change is read with: its type, what the game takes when it is absent, and its "
      "limits. Generated by `mw3 --reference docs/modding-reference.md` from `src/upgrades/reference/`; do not edit it "
      "by hand. A test runs the game's readers over its own files and fails when a reader reads a key this list lacks "
      "or the list names one no reader reads, so it follows the code. How mods work: `docs/modding.md`.\n";
  for (const File& f : files()) {
    s += std::string("\n## ") + f.title + "\n\n";
    s += std::string("- Where: ") + f.where + "\n- Read by: " + f.reader + "\n\n" + f.intro + "\n\n";
    s += "| Key | In | Type | When absent | Limits | What it does |\n|---|---|---|---|---|---|\n";
    for (const Key& k : f.keys)
      s += "| `" + cell(k.key) + "` | " + cell(*k.path ? k.path : "top") + " | " + cell(k.type) + " | " + cell(k.fallback) + " | " +
           cell(k.limits) + " | " + cell(k.meaning) + (k.unchecked ? " (No shipped mission reaches this read: not checked.)" : "") + " |\n";
  }
  return s;
}

